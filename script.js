function setLanguage(lang){
  document.documentElement.lang = lang;
  document.querySelectorAll('[data-i18n]').forEach(el=>{
    const key = el.getAttribute('data-i18n');
    if(translations[key] && translations[key][lang] != null){
      el.innerHTML = translations[key][lang];
    }
  });
  document.querySelectorAll('.lang-btn').forEach(b=>{
    b.classList.toggle('active', b.dataset.lang === lang);
  });
}

document.addEventListener('DOMContentLoaded', () => {
  setLanguage('en');

  // Language switch
  document.querySelectorAll('.lang-btn').forEach(btn=>{
    btn.addEventListener('click', ()=> setLanguage(btn.dataset.lang));
  });

  // Mobile nav toggle
  const navToggle = document.getElementById('navToggle');
  const navLinks = document.getElementById('navLinks');
  if (navToggle && navLinks) {
    navToggle.addEventListener('click', () => {
      const isOpen = navLinks.classList.toggle('open');
      navToggle.setAttribute('aria-expanded', isOpen);
    });
    navLinks.querySelectorAll('a').forEach(a => a.addEventListener('click', () => {
      navLinks.classList.remove('open');
      navToggle.setAttribute('aria-expanded', 'false');
    }));
  }

  // Scroll reveal & Counter Animation
  const prefersReduced = window.matchMedia('(prefers-reduced-motion: reduce)').matches;
  const revealEls = document.querySelectorAll('.reveal, .game-card');
  const counters = document.querySelectorAll('.stat-num, .stat-num-big');
  
  const animateCounter = (el) => {
    const target = parseInt(el.getAttribute('data-target'));
    const duration = 1500; // ms
    const step = target / (duration / 16); // 60fps
    let current = 0;
    
    const isDoubleDigit = el.classList.contains('stat-num-big');

    const updateCounter = () => {
      current += step;
      if (current < target) {
        let val = Math.ceil(current);
        el.innerText = isDoubleDigit && val < 10 ? '0' + val : val;
        requestAnimationFrame(updateCounter);
      } else {
        el.innerText = isDoubleDigit && target < 10 ? '0' + target : target;
      }
    };
    updateCounter();
  };

  if ('IntersectionObserver' in window && !prefersReduced) {
    const io = new IntersectionObserver((entries) => {
      entries.forEach(entry => {
        if (entry.isIntersecting) {
          const delay = entry.target.classList.contains('game-card')
            ? Array.from(document.querySelectorAll('.game-card')).indexOf(entry.target) * 60
            : 0;
          
          setTimeout(() => {
            entry.target.classList.add('visible');
            // Trigger counters inside this element
            entry.target.querySelectorAll('.stat-num, .stat-num-big').forEach(c => animateCounter(c));
            // Or if the element itself is a counter (in hero section)
            if(entry.target.classList.contains('stat-num') || entry.target.classList.contains('stat-num-big')){
              animateCounter(entry.target);
            }
          }, delay);
          
          io.unobserve(entry.target);
        }
      });
    }, { threshold: 0.1 });
    revealEls.forEach(el => io.observe(el));
    
    // Also observe hero stats separately since they might not have .reveal
    counters.forEach(c => {
      if(!c.closest('.reveal')) io.observe(c);
    });
    
  } else {
    revealEls.forEach(el => el.classList.add('visible'));
    counters.forEach(c => c.innerText = c.getAttribute('data-target'));
  }

  // Card hover light tracking
  if (!prefersReduced) {
    document.querySelectorAll('.game-card').forEach(card => {
      card.addEventListener('mousemove', e => {
        const rect = card.getBoundingClientRect();
        card.style.setProperty('--mx', ((e.clientX - rect.left) / rect.width * 100) + '%');
        card.style.setProperty('--my', ((e.clientY - rect.top) / rect.height * 100) + '%');
      });
    });
  }
});
